"""Data for quantum classifiers. A circuit takes one feature per qubit as a rotation angle, so a
table is reduced to as many directions as there are qubits (principal components when it has
more columns, columns repeated when it has fewer) and scaled to [0, π] on the training rows.

Also three small synthetic sets — two moons, circles and XOR — made by scikit-learn's generators
with a fixed seed. They are ordinary tabular datasets, so the Classical ML lab and the 3-D
explorer can use them as well.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any, ClassVar

import numpy as np

from core.common.cancel import CancelToken, ProgressFn
from core.common.optional import is_installed
from core.dataset_registry.adapter import DatasetStats, LocalState, TabularAdapter

__all__ = ["Prepared", "SyntheticAdapter", "prepare"]


class SyntheticAdapter(TabularAdapter):
    """Two moons, circles or XOR: 400 points in two dimensions, two classes, always the same."""

    ROWS: ClassVar[int] = 400

    def local_status(self, root: Path) -> LocalState:
        return "present" if is_installed("scikit-learn") else "absent"

    def _download(self, root: Path, progress: ProgressFn, cancel: CancelToken) -> None:
        raise FileNotFoundError(f"{self.card.name} is generated by scikit-learn: install scikit-learn in the "
                                "experiment Python environment")

    def points(self) -> tuple[np.ndarray, np.ndarray]:
        from sklearn import datasets

        kind = self.card.options.get("generator", self.card.id)
        if kind == "moons":
            return datasets.make_moons(self.ROWS, noise=0.15, random_state=0)
        if kind == "circles":
            return datasets.make_circles(self.ROWS, noise=0.08, factor=0.5, random_state=0)
        if kind == "xor":
            rng = np.random.default_rng(0)
            x = rng.uniform(-1.0, 1.0, (self.ROWS, 2))
            return x, ((x[:, 0] > 0) ^ (x[:, 1] > 0)).astype(int)
        raise ValueError(f"unknown generator {kind!r}")

    def load_frame(self, root: Path) -> tuple[Any, Any]:
        import pandas as pd

        x, y = self.points()
        return pd.DataFrame(x, columns=["x1", "x2"]), pd.Series(y, name="target")

    def class_names(self) -> tuple[str, ...]:
        return tuple(self.card.class_names) or ("class 0", "class 1")

    def describe(self, root: Path) -> DatasetStats:
        return DatasetStats({"all": self.ROWS}, 2, self.class_names(), {"features": ["x1", "x2"]})


@dataclass
class Prepared:
    x_train: np.ndarray
    y_train: np.ndarray
    x_val: np.ndarray
    y_val: np.ndarray
    x_test: np.ndarray
    y_test: np.ndarray
    classes: list[str]
    #: What each qubit's angle is made of: column names, "PC 1"..., or a repeated column.
    angles: list[str]
    #: Share of the variance kept by the principal components (1.0 when none were needed).
    kept_variance: float
    columns: list[str]
    #: Raw rows (the dataset's numeric columns) → angles, as fitted on the training rows.
    transform: Callable[[np.ndarray], np.ndarray] | None = None


def prepare(frame: Any, target: Any, qubits: int, *, seed: int, test_fraction: float, val_fraction: float,
            subset: int | None = None, class_names: tuple[str, ...] = ()) -> Prepared:
    """Numeric columns → (PCA to ``qubits`` | repeat) → [0, π] on the training rows; stratified
    train / validation / test split."""
    from sklearn.decomposition import PCA
    from sklearn.model_selection import train_test_split
    from sklearn.preprocessing import MinMaxScaler, StandardScaler

    if target is None:
        raise ValueError("a quantum classifier needs a dataset with a target column")
    numeric = frame.select_dtypes(include=["number", "bool"])
    keep = numeric.notna().all(axis=1).to_numpy() & target.notna().to_numpy()
    x = numeric.to_numpy(dtype=float)[keep]
    labels = target.to_numpy()[keep]
    values, y = np.unique(labels, return_inverse=True)
    if subset and len(x) > subset:
        index, _ = train_test_split(np.arange(len(x)), train_size=subset, stratify=y, random_state=seed)
        x, y = x[np.sort(index)], y[np.sort(index)]
    if len(values) < 2:
        raise ValueError("the target has only one class")
    names = list(class_names) if class_names and len(class_names) == len(values) else [str(v) for v in values]
    x_rest, x_test, y_rest, y_test = train_test_split(x, y, test_size=test_fraction, stratify=y,
                                                      random_state=seed)
    if val_fraction > 0:
        x_train, x_val, y_train, y_val = train_test_split(x_rest, y_rest, test_size=val_fraction,
                                                          stratify=y_rest,
                                                          random_state=seed)
    else:
        x_train, x_val, y_train, y_val = x_rest, x_rest[:0], y_rest, y_rest[:0]
    columns = [str(c) for c in numeric.columns]
    kept = 1.0
    if x.shape[1] > qubits:
        scaler = StandardScaler().fit(x_train)
        pca = PCA(n_components=qubits, random_state=seed).fit(scaler.transform(x_train))
        kept = float(pca.explained_variance_ratio_.sum())

        def reduce(a: np.ndarray) -> np.ndarray:
            return pca.transform(scaler.transform(a)) if len(a) else np.zeros((0, qubits))

        angles = [f"PC {i + 1}" for i in range(qubits)]
    else:
        repeat = [i % x.shape[1] for i in range(qubits)]

        def reduce(a: np.ndarray) -> np.ndarray:
            return a[:, repeat]

        angles = [columns[i] + (" (again)" if n >= x.shape[1] else "") for n, i in enumerate(repeat)]
    reduced = [reduce(part) for part in (x_train, x_val, x_test)]
    to_angle = MinMaxScaler((0.0, np.pi)).fit(reduced[0])
    x_train, x_val, x_test = (np.clip(to_angle.transform(part), 0, np.pi) if len(part) else part
                              for part in reduced)

    def transform(raw: np.ndarray) -> np.ndarray:
        return np.clip(to_angle.transform(reduce(np.atleast_2d(np.asarray(raw, dtype=float)))), 0, np.pi)

    return Prepared(x_train, y_train, x_val, y_val, x_test, y_test, names, angles, kept, columns, transform)
